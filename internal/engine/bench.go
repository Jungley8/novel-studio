package engine

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/Jungley8/novel-studio/internal/domain"
)

// BenchWordCountPassRatio is the threshold ratio (80%) of target words below which a chapter is marked UnderTarget.
// 数字口径：80% 及格线，章节字数严格低于 target * 0.8 时计入 UnderTarget。
const BenchWordCountPassRatio = 0.8

// BenchEchoWindowSize is the maximum number of preceding chapters evaluated for repetitive echo phrases.
// 数字口径：20 章回声窗口，仅取当前章前序最多 20 章的正文作为最近比对样本。
const BenchEchoWindowSize = 20

// BenchLedgerCaveat is the fixed caveat text for ledger replay audits.
const BenchLedgerCaveat = "重放审计以逐章状态快照链为基线校验增量一致性，无快照覆盖的章节仅记备注跳过；与末章快照不一致的状态视为界面直接修改。"

// BenchWordCount holds chapter length statistics and quota adherence.
type BenchWordCount struct {
	Avg         int `json:"avg"`
	Min         int `json:"min"`
	Max         int `json:"max"`
	Target      int `json:"target"`
	UnderTarget int `json:"under_target"`
}

// BenchChapterTypes holds narrative chapter type distribution and streak analysis.
type BenchChapterTypes struct {
	Distribution   map[string]int `json:"distribution"`
	MaxConsecutive int            `json:"max_consecutive"`
	MaxRunChapters []int          `json:"max_run_chapters"`
}

// OverdueHook represents a plot hook that missed its resolution chapter target.
type OverdueHook struct {
	ID            string            `json:"id"`
	Title         string            `json:"title"`
	TargetChapter int               `json:"target_chapter"`
	Status        domain.HookStatus `json:"status"`
}

// BenchHooks holds lifecycle metrics and overdue plot hook detections.
type BenchHooks struct {
	Open       int           `json:"open"`
	Fermenting int           `json:"fermenting"`
	Resolved   int           `json:"resolved"`
	Abandoned  int           `json:"abandoned"`
	Overdue    []OverdueHook `json:"overdue"`
}

// BenchLedgerReplay holds state machine replay audit results and detected drifts.
type BenchLedgerReplay struct {
	Clean  bool     `json:"clean"`
	Drifts []string `json:"drifts"`
	Notes  []string `json:"notes"`
	Caveat string   `json:"caveat"`
}

// BenchEcho holds cross-chapter repetition detection metrics.
type BenchEcho struct {
	TotalPhrases int `json:"total_phrases"`
	ChaptersHit  int `json:"chapters_hit"`
}

// BenchLint holds read-only aggregates over stored chapter lint/review fields.
// 存量字段只读统计，不跑 LLM/linter。
type BenchLint struct {
	Chapters           int     `json:"chapters"`
	LinterPassed       int     `json:"linter_passed"`
	LinterPassRate     float64 `json:"linter_pass_rate"`
	AvgBurstinessScore float64 `json:"avg_burstiness_score"`
	ReviewCovered      int     `json:"review_covered"`
}

// BenchReport is the quality audit report generated by RunBenchProbes.
type BenchReport struct {
	ProjectID        string            `json:"project_id"`
	ProjectTitle     string            `json:"project_title"`
	Chapters         int               `json:"chapters"`
	WordCount        BenchWordCount    `json:"word_count"`
	ChapterTypes     BenchChapterTypes `json:"chapter_types"`
	Hooks            BenchHooks        `json:"hooks"`
	LedgerReplay     BenchLedgerReplay `json:"ledger_replay"`
	Echo             BenchEcho         `json:"echo"`
	Lint             BenchLint         `json:"lint"`
	StyleVaultSeeded bool              `json:"style_vault_seeded"`
	StyleVaultError  string            `json:"style_vault_error,omitempty"`
}

// benchRealm returns the observable realm of a codex entry
// (StructuredLevel.Realm preferred, Realm fallback, trimmed).
func benchRealm(e *domain.CodexEntry) string {
	if e == nil {
		return ""
	}
	if e.StructuredLevel != nil && strings.TrimSpace(e.StructuredLevel.Realm) != "" {
		return strings.TrimSpace(e.StructuredLevel.Realm)
	}
	return strings.TrimSpace(e.Realm)
}

// benchItemsMap returns the observable inventory as a name→quantity map.
// StructuredItems 可能 nil；空 map 与空背包视为相等。
func benchItemsMap(e *domain.CodexEntry) map[string]int {
	m := make(map[string]int)
	if e == nil {
		return m
	}
	for _, itm := range e.StructuredItems {
		if name := strings.TrimSpace(itm.Name); name != "" {
			m[name] += itm.Quantity
		}
	}
	return m
}

// RunBenchProbes runs deterministic, read-only quality probes across book chapters and project metadata.
// snapshots 为逐章提交后状态快照（snapshot[N] == 第N章提交后状态），用于快照链过渡校验；
// 传 nil 表示无快照数据（此时有 mutation 章节即判无法验证，不空口报 CLEAN）。
func RunBenchProbes(
	project *domain.Project,
	chapters []*domain.Chapter,
	hooks []*domain.PlotHook,
	protagonist *domain.CodexEntry,
	styleVaultSeeded bool,
	snapshots []*domain.ChapterStateSnapshot,
) *BenchReport {
	report := &BenchReport{
		WordCount: BenchWordCount{
			Target: 2000,
		},
		ChapterTypes: BenchChapterTypes{
			Distribution:   make(map[string]int),
			MaxRunChapters: make([]int, 0),
		},
		Hooks: BenchHooks{
			Overdue: make([]OverdueHook, 0),
		},
		LedgerReplay: BenchLedgerReplay{
			Clean:  true,
			Drifts: make([]string, 0),
			Notes:  make([]string, 0),
			Caveat: BenchLedgerCaveat,
		},
		Echo: BenchEcho{
			TotalPhrases: 0,
			ChaptersHit:  0,
		},
		StyleVaultSeeded: styleVaultSeeded,
	}

	if project != nil {
		report.ProjectID = project.ID
		report.ProjectTitle = project.Title
		if project.DefaultWordsTarget > 0 {
			report.WordCount.Target = project.DefaultWordsTarget
		}
	}

	// 6. 防御性升序排序（不信任调用方顺序），过滤空指针
	sortedChapters := make([]*domain.Chapter, 0, len(chapters))
	for _, ch := range chapters {
		if ch != nil {
			sortedChapters = append(sortedChapters, ch)
		}
	}
	sort.Slice(sortedChapters, func(i, j int) bool {
		return sortedChapters[i].ChapterIndex < sortedChapters[j].ChapterIndex
	})
	report.Chapters = len(sortedChapters)

	// 1. WordCount: 逐章统计字数、avg/min/max 与 <80% 及格线统计
	if len(sortedChapters) > 0 {
		minWords := 0
		maxWords := 0
		totalWords := 0
		underTargetCount := 0
		// 及格线下限：target * 0.8
		passThreshold := float64(report.WordCount.Target) * BenchWordCountPassRatio

		for i, ch := range sortedChapters {
			wc := ch.WordCount
			if wc <= 0 {
				wc = len([]rune(ch.Content))
			}
			if i == 0 {
				minWords = wc
				maxWords = wc
			} else {
				if wc < minWords {
					minWords = wc
				}
				if wc > maxWords {
					maxWords = wc
				}
			}
			totalWords += wc
			if float64(wc) < passThreshold {
				underTargetCount++
			}
		}

		report.WordCount.Avg = totalWords / len(sortedChapters)
		report.WordCount.Min = minWords
		report.WordCount.Max = maxWords
		report.WordCount.UnderTarget = underTargetCount
	}

	// 2. ChapterTypes: 分布统计与最长同型连续扫描（无 beats 章跳过并在注释说明）
	var currentType string
	var currentRun []int
	maxConsecutive := 0
	var maxRunChapters []int

	for _, ch := range sortedChapters {
		if len(ch.Beats) == 0 {
			// 无 beats 的章跳过（不纳入分布统计），并打断当前同型连续扫描
			currentType = ""
			currentRun = nil
			continue
		}
		ct := string(domain.ClassifyChapterType(ch.Beats))
		report.ChapterTypes.Distribution[ct]++

		if ct == currentType {
			currentRun = append(currentRun, ch.ChapterIndex)
		} else {
			currentType = ct
			currentRun = []int{ch.ChapterIndex}
		}

		if len(currentRun) > maxConsecutive {
			maxConsecutive = len(currentRun)
			maxRunChapters = make([]int, len(currentRun))
			copy(maxRunChapters, currentRun)
		}
	}
	report.ChapterTypes.MaxConsecutive = maxConsecutive
	if maxRunChapters != nil {
		report.ChapterTypes.MaxRunChapters = maxRunChapters
	}

	// 3. Hooks: 四类计数与逾期审计 (TargetChapter < 最大已归档章号)
	maxChapterIndex := 0
	for _, ch := range sortedChapters {
		if ch.ChapterIndex > maxChapterIndex {
			maxChapterIndex = ch.ChapterIndex
		}
	}

	for _, h := range hooks {
		if h == nil {
			continue
		}
		switch h.Status {
		case domain.HookStatusOpen:
			report.Hooks.Open++
		case domain.HookStatusFermenting:
			report.Hooks.Fermenting++
		case domain.HookStatusResolved:
			report.Hooks.Resolved++
		case domain.HookStatusAbandoned:
			report.Hooks.Abandoned++
		}

		if (h.Status == domain.HookStatusOpen || h.Status == domain.HookStatusFermenting) &&
			h.TargetChapter < maxChapterIndex {
			report.Hooks.Overdue = append(report.Hooks.Overdue, OverdueHook{
				ID:            h.ID,
				Title:         h.Title,
				TargetChapter: h.TargetChapter,
				Status:        h.Status,
			})
		}
	}

	// 4. LedgerReplay: 快照链逐章过渡校验（decode(snapshot[N-1]) + mutation[N] == snapshot[N]）
	// snapshot[N] 为第N章提交后状态；第 1 章无前置快照（与 UncommitChapter"首章前态创世空态"边界一致），跳过并记 Notes。
	if protagonist == nil {
		report.LedgerReplay.Clean = true
		report.LedgerReplay.Caveat = BenchLedgerCaveat + "（无主角实体，跳过）"
	} else {
		drifts := make([]string, 0)
		notes := make([]string, 0)

		snapByIndex := make(map[int]*domain.ChapterStateSnapshot, len(snapshots))
		ignoredFrontier := make([]int, 0)
		ignoredSeen := make(map[int]bool)
		for _, snap := range snapshots {
			if snap == nil {
				continue
			}
			// 正史前沿（maxChapterIndex 为 chapters 下最大章号）之外的快照是
			// UncommitChapter 留下的撤回残留（只删 chapters 行、不删快照行），
			// 一律忽略并记 Notes，不参与过渡与终态校验。
			if snap.ChapterIndex > maxChapterIndex {
				if !ignoredSeen[snap.ChapterIndex] {
					ignoredSeen[snap.ChapterIndex] = true
					ignoredFrontier = append(ignoredFrontier, snap.ChapterIndex)
				}
				continue
			}
			if _, exists := snapByIndex[snap.ChapterIndex]; !exists {
				snapByIndex[snap.ChapterIndex] = snap
			}
		}
		sort.Ints(ignoredFrontier)
		for _, idx := range ignoredFrontier {
			notes = append(notes, fmt.Sprintf("第%d章快照超出正史前沿，视为撤回残留，跳过", idx))
		}

		hasMutation := func(ch *domain.Chapter) bool {
			return strings.TrimSpace(ch.StateMutation.InventoryDelta) != "" ||
				strings.TrimSpace(ch.StateMutation.PowerDelta) != "" ||
				len(ch.StateMutation.CharacterMutations) > 0
		}

		mutationChapters := 0
		verifiedTransitions := 0

		for _, ch := range sortedChapters {
			if !hasMutation(ch) {
				continue
			}
			mutationChapters++

			prevSnap, hasPrev := snapByIndex[ch.ChapterIndex-1]
			currSnap, hasCurr := snapByIndex[ch.ChapterIndex]
			if !hasPrev || !hasCurr {
				notes = append(notes, fmt.Sprintf("第%d章缺前置/后置快照，跳过逐章校验", ch.ChapterIndex))
				continue
			}

			var prevState domain.CodexEntry
			if err := json.Unmarshal([]byte(prevSnap.ProtagonistJSON), &prevState); err != nil {
				drifts = append(drifts, fmt.Sprintf("第%d章前置快照解码失败: %v", ch.ChapterIndex, err))
				continue
			}

			auditTrail, err := domain.ApplyStateMutation(&prevState, ch.StateMutation)
			if err != nil {
				drifts = append(drifts, fmt.Sprintf("第%d章应用失败: %v", ch.ChapterIndex, err))
				continue
			}
			// 此时基线精确，warning 即真异常。
			for _, trail := range auditTrail {
				if strings.Contains(trail, "[Ledger Warning]") || strings.Contains(trail, "实体状态机不一致") {
					drifts = append(drifts, fmt.Sprintf("第%d章应用异常: %s", ch.ChapterIndex, trail))
				}
			}

			var currState domain.CodexEntry
			if err := json.Unmarshal([]byte(currSnap.ProtagonistJSON), &currState); err != nil {
				drifts = append(drifts, fmt.Sprintf("第%d章后置快照解码失败: %v", ch.ChapterIndex, err))
				continue
			}

			// 后态比对：Realm 字符串 + 背包名字→数量 map；StructuredLevel.History 不比。
			if replayed, expected := benchRealm(&prevState), benchRealm(&currState); replayed != expected {
				drifts = append(drifts, fmt.Sprintf("第%d章境界漂移: 重放=%s 快照=%s", ch.ChapterIndex, replayed, expected))
			}

			replayedMap := benchItemsMap(&prevState)
			expectedMap := benchItemsMap(&currState)
			allKeys := make(map[string]struct{})
			for k := range replayedMap {
				allKeys[k] = struct{}{}
			}
			for k := range expectedMap {
				allKeys[k] = struct{}{}
			}
			sortedKeys := make([]string, 0, len(allKeys))
			for k := range allKeys {
				sortedKeys = append(sortedKeys, k)
			}
			sort.Strings(sortedKeys)
			for _, k := range sortedKeys {
				if replayedMap[k] != expectedMap[k] {
					drifts = append(drifts, fmt.Sprintf("第%d章道具「%s」漂移: 重放=%d 快照=%d", ch.ChapterIndex, k, replayedMap[k], expectedMap[k]))
				}
			}

			verifiedTransitions++
		}

		// 终态校验：前沿内最大章快照 vs 当前 protagonist（Realm+背包 map）；无快照时跳过。
		maxSnapIndex := 0
		for idx := range snapByIndex {
			if idx > maxSnapIndex {
				maxSnapIndex = idx
			}
		}
		finalChecked := false
		if maxSnap := snapByIndex[maxSnapIndex]; maxSnapIndex > 0 && maxSnap != nil {
			var lastState domain.CodexEntry
			if err := json.Unmarshal([]byte(maxSnap.ProtagonistJSON), &lastState); err != nil {
				drifts = append(drifts, fmt.Sprintf("末章快照（第%d章）解码失败: %v", maxSnapIndex, err))
				finalChecked = true
			} else {
				finalChecked = true
				if snapRealm, currRealm := benchRealm(&lastState), benchRealm(protagonist); snapRealm != currRealm {
					drifts = append(drifts, fmt.Sprintf("终态境界与末章快照不一致，疑似界面直接修改: 末章快照=%s 当前=%s", snapRealm, currRealm))
				}
				snapMap := benchItemsMap(&lastState)
				currMap := benchItemsMap(protagonist)
				allKeys := make(map[string]struct{})
				for k := range snapMap {
					allKeys[k] = struct{}{}
				}
				for k := range currMap {
					allKeys[k] = struct{}{}
				}
				sortedKeys := make([]string, 0, len(allKeys))
				for k := range allKeys {
					sortedKeys = append(sortedKeys, k)
				}
				sort.Strings(sortedKeys)
				for _, k := range sortedKeys {
					if snapMap[k] != currMap[k] {
						drifts = append(drifts, fmt.Sprintf("终态道具「%s」与末章快照不一致，疑似界面直接修改: 末章快照=%d 当前=%d", k, snapMap[k], currMap[k]))
					}
				}
			}
		}

		// Clean 语义：诊断工具永不空口报 CLEAN。
		if executed := verifiedTransitions > 0 || finalChecked; !executed {
			if len(sortedChapters) == 0 {
				report.LedgerReplay.Clean = true
				notes = append(notes, "无章节数据，跳过账本重放校验")
			} else if mutationChapters == 0 {
				report.LedgerReplay.Clean = true
				notes = append(notes, "无状态增量章节，跳过逐章校验")
			} else {
				report.LedgerReplay.Clean = false
				notes = append(notes, "无快照数据，无法验证")
			}
		} else {
			report.LedgerReplay.Clean = (len(drifts) == 0)
		}
		report.LedgerReplay.Drifts = drifts
		report.LedgerReplay.Notes = notes
		report.LedgerReplay.Caveat = BenchLedgerCaveat
	}

	// 5. Echo: 前序最多 20 章回声探测
	totalPhrases := 0
	chaptersHit := 0

	for i := 0; i < len(sortedChapters); i++ {
		content := sortedChapters[i].Content
		if strings.TrimSpace(content) == "" {
			continue // 空章跳过
		}

		start := 0
		if i > BenchEchoWindowSize {
			start = i - BenchEchoWindowSize
		}

		recentTexts := make([]string, 0, i-start)
		for j := start; j < i; j++ {
			recentTexts = append(recentTexts, sortedChapters[j].Content)
		}

		hits := DetectEchoPhrases(recentTexts, content)
		if len(hits) > 0 {
			totalPhrases += len(hits)
			chaptersHit++
		}
	}

	report.Echo.TotalPhrases = totalPhrases
	report.Echo.ChaptersHit = chaptersHit

	// 6. Lint: 存量字段只读统计（LinterPassed 通过率 + BurstinessScore 均值 + Review 覆盖章数），不跑 LLM/linter。
	lintPassed := 0
	burstSum := 0
	reviewCovered := 0
	for _, ch := range sortedChapters {
		if ch.LinterPassed {
			lintPassed++
		}
		burstSum += ch.BurstinessScore
		if ch.Review != nil {
			reviewCovered++
		}
	}
	report.Lint.Chapters = len(sortedChapters)
	report.Lint.LinterPassed = lintPassed
	report.Lint.ReviewCovered = reviewCovered
	if len(sortedChapters) > 0 {
		report.Lint.LinterPassRate = float64(lintPassed) / float64(len(sortedChapters))
		report.Lint.AvgBurstinessScore = float64(burstSum) / float64(len(sortedChapters))
	}

	return report
}
